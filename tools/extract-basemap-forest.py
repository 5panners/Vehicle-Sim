#!/usr/bin/env python3
"""
Forest / open-ground grid from a north-up web-map screenshot (pale green = woodland, white/grey = open ground),
placed in the world with the pixel->world transform that tools/build-spa-track.py saved next to the centreline.

  python3 tools/extract-basemap-forest.py tools/reference/spa-forest.json

Writes an ES module with the grid run-length encoded: 0 open ground, 1 woodland. Outside the picture the
land is taken to be woodland (the Ardennes). A 3x3 majority filter removes tree icons, text and road casings.
"""
import json, math, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from lib_png import read_png


def forest(r, g, b):
    return g > r + 22 and g > b + 12 and min(r, g, b) > 95 and max(r, g, b) > 150


def main(cfg):
    W, H, rows = read_png(cfg['image'])
    T = json.loads(re.search(r'TRANSFORM = (\{.*?\});', open(cfg['trackModule']).read()).group(1))
    k, cx, cz, sc = T['pxPerM'], T['cx'], T['cz'], T['k']
    skip = cfg.get('ignore', [])
    size, res = cfg.get('size', 2400), cfg.get('res', 4); n = int(size / res) + 1; half = size / 2
    grid = [[1] * n for _ in range(n)]
    inside = 0
    for j in range(n):
        for i in range(n):
            x, z = i * res - half, j * res - half
            X, Z = x / sc + cx, z / sc + cz
            px, py = -X * k, -Z * k
            if 0 <= px < W and 0 <= py < H and not any(a <= px <= c and b <= py <= d for a, b, c, d in skip):
                grid[j][i] = 1 if forest(*rows[int(py)][int(px)]) else 0; inside += 1
    for _ in range(3):
        out = [r[:] for r in grid]
        for j in range(1, n - 1):
            for i in range(1, n - 1):
                s = sum(grid[j + dj][i + di] for dj in (-1, 0, 1) for di in (-1, 0, 1)); out[j][i] = 1 if s >= 5 else 0
        grid = out
    flat = [v for r in grid for v in r]; rle = []; run = 1
    for a, b in zip(flat, flat[1:] + [None]):
        if a == b: run += 1
        else: rle.append(f'{a}{run}.'); run = 1
    with open(cfg['out'], 'w') as f:
        f.write(f"// Generated by tools/extract-basemap-forest.py from {os.path.basename(cfg['image'])} - do not edit by hand.\n")
        f.write(f"// Woodland grid {n}x{n} at {res} m over {size} m. 0 open ground, 1 woodland (also outside the picture).\n")
        f.write(f"export const FOREST = {{ n: {n}, res: {res}, size: {size}, rle: '{''.join(rle)}' }};\n")
        f.write("export function decodeForest() {\n  const out = new Uint8Array(FOREST.n * FOREST.n); let p = 0, i = 0; const s = FOREST.rle;\n"
                "  while (i < s.length) { const v = +s[i++]; let c = ''; while (s[i] !== '.') c += s[i++]; i++; out.fill(v, p, p + +c); p += +c; }\n  return out;\n}\n")
    print(f'{n}x{n} cells, {inside} sampled from the picture, woodland {sum(flat) / len(flat) * 100:.0f}%, rle {sum(len(x) for x in rle)} chars')


if __name__ == '__main__':
    main(json.load(open(sys.argv[1])))
