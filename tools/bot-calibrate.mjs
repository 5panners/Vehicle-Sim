// Calibrates the practice bot per car and circuit: an Alien bot laps until it stops having moments,
// and the grip it settles on (as a fraction of the tyre's peak) is written to src/game/botCalibration.js.
//   node tools/bot-calibrate.mjs <mapId> <car name> [laps]   -> prints one JSON line
//   node tools/bot-calibrate.mjs --write <results.jsonl>      -> writes the calibration module
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

if (process.argv[2] === '--write') {
  const table = {};
  for (const line of readFileSync(process.argv[3], 'utf8').split('\n').filter(Boolean)) {
    const r = JSON.parse(line); (table[r.map] ??= {})[r.car] = r.ratio;
  }
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'game', 'botCalibration.js');
  writeFileSync(out, `// Generated by tools/bot-calibrate.mjs - learned bot grip as a fraction of each car's tyre peak, per circuit.\nexport const BOT_CALIBRATION = ${JSON.stringify(table, null, 2)};\n`);
  console.log('wrote', out);
  process.exit(0);
}

const { World } = await import('../src/world/World.js');
const { MAPS } = await import('../src/world/maps/index.js');
const { Vehicle } = await import('../src/physics/Vehicle.js');
const { PRESETS } = await import('../src/vehicles/presets.js');
const { LapTimer } = await import('../src/game/LapTimer.js');
const { BotDriver, BOT_SKILLS } = await import('../src/game/BotDriver.js');
const mapId = process.argv[2], carName = process.argv[3], LAPS = +(process.argv[4] || 5), DT = 1 / 600;
const world = new World(MAPS[mapId]);
const car = new Vehicle(structuredClone(PRESETS.find((p) => p.name === carName)), world);
const bot = new BotDriver(world, car, BOT_SKILLS[BOT_SKILLS.length - 1], { calibrated: false });
bot.placeAt(world.track.length - 40);
const lt = new LapTimer(world), laps = [];
let lapMoments = [], m0 = 0;
for (let i = 0; i < (LAPS * 260) / DT && laps.length < LAPS; i++) {
  bot.drive(DT, null); car.step(DT); car.wallContact = null;
  if (lt.update(DT, car.body.position.x, car.body.position.z) === 'lap') { laps.push(+lt.last.time.toFixed(2)); lapMoments.push((bot.moments || 0) - m0); m0 = bot.moments || 0; }
}
console.log(JSON.stringify({ map: mapId, car: carName, ratio: +(bot.carGrip / bot.peak).toFixed(3), laps, lapMoments, resets: bot.resets || 0 }));
