// Writes src/build.js with the next build number (= commit count including the next commit) and today's date.
// Run before committing:  npm run bump
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

let count = 0;
try { count = +execSync('git rev-list --count HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* no commits yet */ }
const number = count + 1, date = new Date().toISOString().slice(0, 10);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'build.js');
writeFileSync(out, `// Generated by tools/bump-build.mjs (npm run bump) - do not edit by hand.\nexport const BUILD = { number: ${number}, date: '${date}' };\n`);
console.log(`build ${number} (${date})`);
