#!/usr/bin/env python3
"""
Turn a circuit layout map into a world-space land-use grid, so a map's coastline, parks and
building footprints sit exactly where the diagram has them relative to the track.

  python3 tools/extract-map-masks.py tools/reference/<circuit>-masks.json

Reads the same image the track was traced from, plus the TRANSFORM that tools/extract-track.py
saved next to the centreline (pixel -> world), classifies pixels by colour, resamples them onto
a regular world grid (nearest pixel, then a 3x3 majority filter to remove labels and icons) and
writes an ES module with the grid run-length encoded.

Classes: 0 land/road, 1 water, 2 park (green), 3 building (yellow), 4 grandstand (red).
Outside the diagram the edge is extended (clamped), so the land and sea carry on past the map.
"""
import json, math, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from lib_png import read_png, write_png

WATER, PARK, BUILDING, STAND = 1, 2, 3, 4


def classify(r, g, b):
    if b > 195 and r < 160 and g > 150 and b - r > 55: return WATER
    if r > 215 and g < 100 and b < 100: return STAND                                  # red grandstand blocks
    if r > 225 and g > 205 and b < 170 and r - b > 70: return BUILDING                 # pale yellow footprints
    if g > r + 18 and g > b + 35 and r < 200: return PARK                             # parks / gardens
    return 0


def main(cfg):
    W, H, rows = read_png(cfg['image'])
    src = open(cfg['trackModule']).read()
    T = json.loads(re.search(r'TRANSFORM = (\{.*?\});', src).group(1))
    s, th, cx, cz, k = T['s'], math.radians(T['thDeg']), T['cx'], T['cz'], T['k']
    y0, y1 = cfg.get('rowRange', [0, H])                                              # crop away the header / legend
    cls = [[classify(*rows[y][x]) if y0 <= y < y1 else 0 for x in range(W)] for y in range(H)]
    size, res = cfg.get('size', 1600), cfg.get('res', 2)
    n = int(size / res) + 1; half = size / 2
    grid = [[0] * n for _ in range(n)]
    for j in range(n):
        for i in range(n):
            x, z = i * res - half, j * res - half
            X, Z = x / k + cx, z / k + cz                                             # undo the final scale and centring
            e2, n2 = -X, Z
            e = e2 * math.cos(th) - n2 * math.sin(th); nn = e2 * math.sin(th) + n2 * math.cos(th)
            u, v = e / s, -nn / s
            px = min(W - 1, max(0, int(round(u)))); py = min(y1 - 1, max(y0, int(round(v))))
            grid[j][i] = cls[py][px]
    # 3x3 majority filter (twice) to drop text, icons and anti-aliasing speckle
    for _ in range(2):
        out = [row[:] for row in grid]
        for j in range(1, n - 1):
            for i in range(1, n - 1):
                c = {}
                for dj in (-1, 0, 1):
                    for di in (-1, 0, 1):
                        v = grid[j + dj][i + di]; c[v] = c.get(v, 0) + 1
                out[j][i] = max(c, key=lambda q: (c[q], q == grid[j][i]))
        grid = out
    # run-length encode row-major as "value:count" pairs in a compact string
    flat = [v for row in grid for v in row]; rle = []; run = 1
    for a, b in zip(flat, flat[1:] + [None]):
        if a == b: run += 1
        else: rle.append(f'{a}{run}' if run > 1 else f'{a}'); run = 1
    # (digit class char, then optional count terminated by '.'): "1" alone = one cell
    enc = ''.join(f'{c[0]}{c[1:]}.' if len(c) > 1 else c[0] + '.' for c in rle)
    with open(cfg['out'], 'w') as f:
        f.write(f"// Generated by tools/extract-map-masks.py from {os.path.basename(cfg['image'])} - do not edit by hand.\n")
        f.write(f"// Land-use grid {n}x{n} at {res} m over {size} m. 0 land, 1 water, 2 park, 3 building, 4 grandstand.\n")
        f.write(f"export const MASK = {{ n: {n}, res: {res}, size: {size}, rle: '{enc}' }};\n")
        f.write("export function decodeMask() {\n  const out = new Uint8Array(MASK.n * MASK.n); let p = 0, i = 0;\n"
                "  const s = MASK.rle;\n  while (i < s.length) { const v = +s[i++]; let c = ''; while (s[i] !== '.') c += s[i++]; i++; const n = c ? +c : 1; out.fill(v, p, p + n); p += n; }\n  return out;\n}\n")
    print(f'{n}x{n} cells, rle {len(enc)} chars,', {c: sum(r.count(c) for r in grid) for c in range(5)})
    if cfg.get('debugImage'):                                                          # colour-coded grid with the track on top
        pal = {0: (235, 235, 230), 1: (90, 160, 215), 2: (130, 180, 90), 3: (240, 210, 90), 4: (210, 50, 50)}
        img = [[pal[v] for v in row] for row in grid]
        pts = [tuple(map(float, m)) for m in re.findall(r'\[(-?[\d.]+), (-?[\d.]+)\]', src.split('CENTERLINE')[1])]
        for x, z in pts:
            i, j = int(round((x + half) / res)), int(round((z + half) / res))
            if 0 <= i < n and 0 <= j < n: img[j][i] = (20, 20, 20)
        write_png(cfg['debugImage'], img[::-1])                                        # +Z (north) up


if __name__ == '__main__':
    main(json.load(open(sys.argv[1])))
